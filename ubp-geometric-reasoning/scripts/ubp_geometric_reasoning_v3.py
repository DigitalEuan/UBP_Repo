class UBPVectorEngine:
    """
    Handles vector generation using the CORRECT UBP protocol:
    1. For known concepts: Load from system_kb (lookup)
    2. For new concepts: Hash-based generation with Golay encoding
    """
    
    def __init__(self, system_kb_path: Optional[str] = None):
        """Initialize with optional system_kb path."""
        self.golay = GOLAY_DECODER
        self.system_kb = {}
        self.vector_cache = {}
        
        # Load system_kb if available
        if system_kb_path and os.path.exists(system_kb_path):
            self._load_system_kb(system_kb_path)
        
        # Try to load from hex_dictionary
        try:
            self.hex_db = HEX_DB_EXACT
            print(f"[VECTOR ENGINE] Loaded HexDB with {len(self.hex_db.registry)} entries")
        except:
            self.hex_db = None
            print("[VECTOR ENGINE] HexDB not available, using hash-based generation")
    
    def _load_system_kb(self, path: str):
        """Load system_kb and extract vectors."""
        try:
            with open(path, 'r') as f:
                data = json.load(f)
            
            for fingerprint, entry in data.items():
                name = entry.get('name', '')
                ubp_id = entry.get('ubp_id', '')
                vector = entry.get('vector', [])
                
                if vector and len(vector) == 24:
                    # Store by multiple keys for flexible lookup
                    self.system_kb[ubp_id] = vector
                    self.system_kb[name.lower()] = vector
                    self.system_kb[fingerprint] = vector
                    self.vector_cache[ubp_id] = vector
            
            print(f"[VECTOR ENGINE] Loaded {len(self.system_kb)} vectors from system_kb")
        except Exception as e:
            print(f"[VECTOR ENGINE] Could not load system_kb: {e}")
    
    def word_to_vector(self, word: str) -> List[int]:
        """
        Convert word to 24-bit vector using the CORRECT UBP protocol.
        
        Protocol (from ubp_integrated_engine_v1.py):
        1. SHA-256 hash the word
        2. Take first 3 bytes → mod 4096 (12-bit space)
        3. Expand to 24 bits
        4. Golay DECODE (error correct)
        5. Golay ENCODE (snap to valid codeword)
        
        This is the "Reflexive Logic": Repair(v) = Encode(Decode(v))
        """
        # Check if we have this in system_kb first
        word_lower = word.lower()
        if word_lower in self.system_kb:
            return self.system_kb[word_lower]
        
        # Check hex_db
        if self.hex_db:
            vec = self.hex_db.get_vector(word)
            if vec:
                return vec
        
        # Generate using hash-based method
        h = hashlib.sha256(word_lower.encode()).digest()
        val = int.from_bytes(h[:3], 'big') % 4096
        raw = [(val >> i) & 1 for i in range(23, -1, -1)]
        cw, _, _ = self.golay.decode(raw)
        return self.golay.encode(cw)
    
    def get_vector_by_id(self, ubp_id: str) -> Optional[List[int]]:
        """Get vector by UBP_ID from system_kb or hex_db."""
        if ubp_id in self.vector_cache:
            return self.vector_cache[ubp_id]
        
        if self.hex_db:
            return self.hex_db.get_vector(ubp_id)
        
        return None
    
    def hamming_distance(self, v1: List[int], v2: List[int]) -> int:
        """Calculate Hamming distance between two vectors."""
        return sum(a != b for a, b in zip(v1, v2))
    
    def snap_to_lattice(self, noisy_vector: List[int]) -> Tuple[List[int], int]:
        """
        Apply reflexive error correction: Repair(v) = Encode(Decode(v))
        Returns: (corrected_vector, errors_fixed)
        """
        if len(noisy_vector) != 24:
            raise ValueError(f"Vector must be 24 bits, got {len(noisy_vector)}")
        
        # Decode to find nearest valid codeword
        message, syndrome, errors = self.golay.decode(noisy_vector)
        
        # Re-encode to get the corrected vector
        corrected = self.golay.encode(message)
        
        # Count errors fixed
        errors_fixed = self.hamming_distance(noisy_vector, corrected)
        
        return corrected, errors_fixed


