class UBPGeometricReasoningV3:
    """
    Complete UBP Geometric Reasoning Engine V3 - System Compatible.
    
    All 8 capabilities now use CORRECT vector handling.
    """
    
    def __init__(self, system_kb_path: Optional[str] = None):
        """Initialize the reasoning engine."""
        if not CORE_AVAILABLE:
            raise ImportError("Core UBP modules required")
        
        self.vector_engine = UBPVectorEngine(system_kb_path)
        self.golay = GOLAY_DECODER
        self.nrci_calc = NRCI_CALCULATOR
        self.leech = UBPUltimateSubstrate()
        
        print("[UBP V3] Geometric Reasoning Engine initialized")
        print(f"  - Vector Engine: Ready")
        print(f"  - Golay Decoder: Ready")
        print(f"  - NRCI Calculator: Ready")
        print(f"  - Leech Lattice: Λ₂₄ ready")
    
    # ==========================================================================
    # CAPABILITY 1: Vectorize Concept
    # ==========================================================================
    
    def vectorize_concept(self, concept: str) -> Dict[str, Any]:
        """
        Vectorize a concept using the CORRECT UBP protocol.
        
        Returns:
            dict with 'vector', 'fingerprint', 'domain', 'nrci', 'hamming_weight'
        """
        # Get vector using correct method
        vector = self.vector_engine.word_to_vector(concept)
        
        # Calculate fingerprint
        fingerprint = hashlib.sha256(concept.lower().encode()).hexdigest()
        
        # Decode to get message
        message, syndrome, errors = self.golay.decode(vector)
        
        # Extract domain from first 3 bits
        domain_bits = message[0:3]
        domain_val = sum(b << (2-i) for i, b in enumerate(domain_bits))
        domains = ["SUBSTANCE", "MECHANISM", "ORGANISM", "ALGORITHM",
                   "QUANTITY", "IMPERATIVE", "ENTROPY", "MEANING"]
        domain = domains[domain_val] if domain_val < len(domains) else "UNKNOWN"
        
        # Calculate NRCI
        nrci_result = self.nrci_calc.calculate_nrci(vector)
        nrci = nrci_result.global_nrci
        
        # Hamming weight
        hamming_weight = sum(vector)
        
        return {
            'concept': concept,
            'vector': vector,
            'fingerprint': fingerprint,
            'domain': domain,
            'nrci': float(nrci),
            'hamming_weight': hamming_weight,
            'errors_corrected': errors,
            'is_valid_codeword': syndrome
        }
    
    # ==========================================================================
    # CAPABILITY 2: Reason About
    # ==========================================================================
    
    def reason_about(self, query: str) -> Dict[str, Any]:
        """
        Execute full reasoning pipeline on a query.
        
        Pipeline:
        1. Vectorize query
        2. Check coherence
        3. Find resonance
        4. Return assessment
        """
        # Vectorize
        vec_result = self.vectorize_concept(query)
        vector = vec_result['vector']
        
        # Calculate coherence
        coherence = self.calculate_coherence(vector)
        
        # Find nearest concepts in system_kb
        resonance = self._find_resonance(vector)
        
        # Observer assessment
        status = "ACCEPTED" if coherence['nrci'] > 0.5 else "REJECTED"
        
        return {
            'status': status,
            'concept': query.upper(),
            'vector': vector,
            'vector_hex': ''.join(f"{b}" for b in vector),
            'resonance': resonance,
            'coherence': coherence,
            'domain': vec_result['domain']
        }
    
    def _find_resonance(self, vector: List[int]) -> Dict[str, Any]:
        """Find nearest concepts in system_kb."""
        if not self.vector_engine.system_kb:
            return {'status': 'NO_KB'}
        
        nearest = []
        for name, kb_vec in list(self.vector_engine.system_kb.items())[:100]:
            if isinstance(kb_vec, list) and len(kb_vec) == 24:
                dist = self.vector_engine.hamming_distance(vector, kb_vec)
                nearest.append({'name': name, 'distance': dist})
        
        nearest.sort(key=lambda x: x['distance'])
        
        if nearest:
            best = nearest[0]
            if best['distance'] == 0:
                return {'anchor': best['name'], 'distance': 0, 'type': 'PERFECT'}
            elif best['distance'] <= 3:
                return {'anchor': best['name'], 'distance': best['distance'], 'type': 'CLOSE'}
            else:
                return {'anchor': best['name'], 'distance': best['distance'], 'type': 'DISTANT'}
        
        return {'status': 'NO_MATCH'}
    
    # ==========================================================================
    # CAPABILITY 3: Find Counterpart
    # ==========================================================================
    
    def find_counterpart(self, concept: str, target_domain: str) -> Dict[str, Any]:
        """
        Find geometric equivalent in a different domain.
        """
        # Vectorize source
        source_vec = self.vector_engine.word_to_vector(concept)
        
        # Search system_kb for concepts in target domain
        candidates = []
        for name, vec in self.vector_engine.system_kb.items():
            if isinstance(vec, list) and len(vec) == 24:
                # Check domain
                msg, _, _ = self.golay.decode(vec)
                domain_bits = msg[0:3]
                domain_val = sum(b << (2-i) for i, b in enumerate(domain_bits))
                domains = ["SUBSTANCE", "MECHANISM", "ORGANISM", "ALGORITHM",
                           "QUANTITY", "IMPERATIVE", "ENTROPY", "MEANING"]
                domain = domains[domain_val] if domain_val < len(domains) else "UNKNOWN"
                
                if domain.upper() == target_domain.upper():
                    dist = self.vector_engine.hamming_distance(source_vec, vec)
                    candidates.append({'name': name, 'distance': dist, 'vector': vec})
        
        if candidates:
            candidates.sort(key=lambda x: x['distance'])
            best = candidates[0]
            return {
                'source_concept': concept,
                'target_domain': target_domain,
                'counterpart': best['name'],
                'hamming_distance': best['distance'],
                'status': 'FOUND'
            }
        
        return {
            'source_concept': concept,
            'target_domain': target_domain,
            'status': 'NOT_FOUND'
        }
    
    # ==========================================================================
    # CAPABILITY 4: Calculate Coherence
    # ==========================================================================
    
    def calculate_coherence(self, vector: List[int]) -> Dict[str, Any]:
        """
        Calculate NRCI and tetradic health.
        """
        nrci_result = self.nrci_calc.calculate_nrci(vector)
        
        return {
            'nrci': float(nrci_result.global_nrci),
            'health': {
                'reality': float(nrci_result.reality_health),
                'info': float(nrci_result.info_health),
                'activation': float(nrci_result.activation_health),
                'potential': float(nrci_result.potential_health)
            },
            'regime': nrci_result.coherence_regime,
            'stability': float(nrci_result.stability_score),
            'symmetry_tax': float(nrci_result.symmetry_tax)
        }
    
    # ==========================================================================
    # CAPABILITY 5: Snap to Lattice
    # ==========================================================================
    
    def snap_to_lattice(self, noisy_vector: List[int]) -> Dict[str, Any]:
        """
        Apply Golay error correction.
        """
        corrected, errors_fixed = self.vector_engine.snap_to_lattice(noisy_vector)
        
        # Find nearest anchor
        resonance = self._find_resonance(corrected)
        
        status = "PERFECT" if errors_fixed == 0 else "CORRECTED" if errors_fixed <= 3 else "DEEP_HOLE"
        
        return {
            'original_vector': noisy_vector,
            'corrected_vector': corrected,
            'errors_fixed': errors_fixed,
            'status': status,
            'nearest_anchor': resonance.get('anchor', 'NONE')
        }
    
    # ==========================================================================
    # CAPABILITY 6: Query Memory
    # ==========================================================================
    
    def query_memory(self, search_term: str, max_results: int = 12) -> List[Dict[str, Any]]:
        """
        Query system_kb by Hamming distance.
        """
        search_vec = self.vector_engine.word_to_vector(search_term)
        
        results = []
        for name, vec in self.vector_engine.system_kb.items():
            if isinstance(vec, list) and len(vec) == 24:
                dist = self.vector_engine.hamming_distance(search_vec, vec)
                results.append({
                    'name': name,
                    'hamming_distance': dist,
                    'vector': vec
                })
        
        results.sort(key=lambda x: x['hamming_distance'])
        return results[:max_results]
    
    # ==========================================================================
    # CAPABILITY 7: Validate Concept
    # ==========================================================================
    
    def validate_concept(self, concept_data: dict) -> Dict[str, Any]:
        """
        Run concept through 5-phase research protocol.
        """
        # Phase 1: Initiation
        required_fields = ['name', 'math', 'language', 'script', 'tags']
        phase1 = 'PASS' if all(f in concept_data for f in required_fields) else 'FAIL'
        
        if phase1 == 'FAIL':
            return {
                'phase_1_initiation': 'FAIL',
                'phase_2_development': 'SKIPPED',
                'phase_3_distillation': 'SKIPPED',
                'phase_4_promotion': 'SKIPPED',
                'phase_5_archival': 'SKIPPED',
                'promotion_eligible': False
            }
        
        # Phase 2: Development (vectorize)
        vec_result = self.vectorize_concept(concept_data['name'])
        phase2 = 'PASS'
        
        # Phase 3: Distillation (coherence check)
        coherence = self.calculate_coherence(vec_result['vector'])
        phase3 = f"PASS (Coherent)" if coherence['nrci'] > 0.5 else "FAIL (Incoherent)"
        
        # Phase 4: Promotion
        phase4 = 'PASS' if coherence['nrci'] > 0.5 else 'FAIL'
        
        # Phase 5: Archival
        phase5 = 'READY' if phase4 == 'PASS' else 'NOT_READY'
        
        return {
            'phase_1_initiation': phase1,
            'phase_2_development': phase2,
            'phase_3_distillation': phase3,
            'phase_4_promotion': phase4,
            'phase_5_archival': phase5,
            'promotion_eligible': phase4 == 'PASS',
            'nrci': coherence['nrci'],
            'vector': vec_result['vector']
        }
    
    # ==========================================================================
    # CAPABILITY 8: Archive to KB
    # ==========================================================================
    
    def archive_to_kb(self, concept_data: dict) -> str:
        """
        Format concept for KB archival.
        """
        # Generate vector
        name = concept_data.get('name', 'UNKNOWN')
        vec_result = self.vectorize_concept(name)
        
        # Create KB entry
        entry = {
            vec_result['fingerprint']: {
                'ubp_id': concept_data.get('ubp_id', f"CUSTOM_{name.upper()}"),
                'name': name,
                'math': concept_data.get('math', ''),
                'language': concept_data.get('language', ''),
                'script': concept_data.get('script', ''),
                'tags': concept_data.get('tags', []),
                'nrci': str(Fraction(vec_result['nrci']).limit_denominator()),
                'fingerprint': vec_result['fingerprint'],
                'vector': vec_result['vector']
            }
        }
        
        return json.dumps(entry, indent=2)


