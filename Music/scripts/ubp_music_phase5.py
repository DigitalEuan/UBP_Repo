def run_vd():
    print(f"\n{'=' * 80}")
    print("PHASE V-D: MAJOR 7TH ANOMALY — Why does C-E-G-B XOR to weight 0?")
    print(f"{'=' * 80}")

    cw_map = encode_pitch_cw_map(COF_ORDER)

    # C=0, E=4, G=7, B=11
    maj7 = [0, 4, 7, 11]
    print(f"\n  CoF positions: {[COF_ORDER.index(p) for p in maj7]}")
    print(f"  CoF names:     {[PITCH_NAMES[p] for p in maj7]}")

    # The XOR of all 4 codewords
    result = list(cw_map[0])
    for pc in maj7[1:]:
        result = [a ^ b for a, b in zip(result, cw_map[pc])]
    print(f"  XOR result HW: {sum(result)}")
    print(f"  XOR result:    {result}")

    # This is weight 0 because in the linear code, C⊕E⊕G⊕B = 0
    # This means B is the XOR of C, E, and G — i.e., B "completes" the triad
    # to form a codeword-equivalent-to-zero structure.
    # Let's verify:
    xor_ceg = [a ^ b ^ c for a, b, c in zip(cw_map[0], cw_map[4], cw_map[7])]
    print(f"\n  C ⊕ E ⊕ G HW: {sum(xor_ceg)}")
    print(f"  B codeword HW: {sum(cw_map[11])}")
    print(f"  (C⊕E⊕G) == B?  {xor_ceg == cw_map[11]}")

    if xor_ceg == cw_map[11]:
        print(f"\n  ★ CONFIRMED: In CoF Gray encoding, B = C ⊕ E ⊕ G")
        print(f"  This means the Major 7th chord is a 'closed group' under XOR —")
        print(f"  it XORs to the identity (weight 0). In UBP terms, this chord")
        print(f"  collapses to the OnBit (NRCI=1.0), the most stable possible state.")
        print(f"  This is a genuine structural property of the CoF-Golay mapping.")

    # Check which other 4-note chords also XOR to 0
    print(f"\n  ALL 4-NOTE CHORDS THAT XOR TO WEIGHT 0:")
    count = 0
    for combo in combinations(range(12), 4):
        result = list(cw_map[combo[0]])
        for pc in combo[1:]:
            result = [a ^ b for a, b in zip(result, cw_map[pc])]
        if sum(result) == 0:
            count += 1
            names = [PITCH_NAMES[p] for p in combo]
            # Identify chord type
            intervals = sorted([min((b-a)%12, (a-b)%12) for a, b in combinations(combo, 2)])
            print(f"    {names} — intervals: {intervals}")
    print(f"  Total: {count} out of C(12,4) = 495")

    # Check which 3-note chords XOR to 0
    print(f"\n  ALL 3-NOTE CHORDS THAT XOR TO WEIGHT 0:")
    count3 = 0
    for combo in combinations(range(12), 3):
        result = list(cw_map[combo[0]])
        for pc in combo[1:]:
            result = [a ^ b for a, b in zip(result, cw_map[pc])]
        if sum(result) == 0:
            count3 += 1
            names = [PITCH_NAMES[p] for p in combo]
            intervals = sorted([min((b-a)%12, (a-b)%12) for a, b in combinations(combo, 2)])
            print(f"    {names} — intervals: {intervals}")
    print(f"  Total: {count3} out of C(12,3) = 220")


