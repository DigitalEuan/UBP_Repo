def pearson_r(x_vals, y_vals):
    n = len(x_vals)
    if n < 2: return 0.0
    mx, my = sum(x_vals)/n, sum(y_vals)/n
    cov = sum((x-mx)*(y-my) for x,y in zip(x_vals, y_vals))
    vx = sum((x-mx)**2 for x in x_vals)
    vy = sum((y-my)**2 for y in y_vals)
    if vx == 0 or vy == 0: return 0.0
    return cov / math.sqrt(vx * vy)


def encode_pitch_cw_map(perm):
    """Given a permutation [pitch_at_pos_0, pitch_at_pos_1, ...], return {pc: cw24}."""
    cw_map = {}
    for pitch_class in range(12):
        pos = perm.index(pitch_class)
        seed = gray_code(pos, 12)
        cw_map[pitch_class] = g.encode(seed)
    return cw_map


def interval_correlation(cw_map, full_range=False):
    """
    Compute Pearson r between consonance rank and Hamming distance.
    If full_range=True, uses intervals 1-11. Otherwise 1-6 (unordered).
    """
    by_interval = {}
    for pc_a, pc_b in combinations(range(12), 2):
        st_f = (pc_b - pc_a) % 12  # forward interval
        st_b = (pc_a - pc_b) % 12  # backward interval
        if full_range:
            # Use both directions to get all 11 intervals
            for st in [st_f, st_b]:
                if st == 0: continue
                hd = sum(x ^ y for x, y in zip(cw_map[pc_a], cw_map[pc_b]))
                by_interval.setdefault(st, []).append(hd)
        else:
            st = min(st_f, st_b)
            if st == 0: continue
            hd = sum(x ^ y for x, y in zip(cw_map[pc_a], cw_map[pc_b]))
            by_interval.setdefault(st, []).append(hd)

    x_vals, y_vals = [], []
    st_range = range(1, 12) if full_range else range(1, 7)
    for st in st_range:
        hds = by_interval.get(st, [])
        if not hds: continue
        x_vals.append(CONSONANCE_RANK[st])
        y_vals.append(sum(hds) / len(hds))
    return pearson_r(x_vals, y_vals)


