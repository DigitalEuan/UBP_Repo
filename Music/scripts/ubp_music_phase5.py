def analyze_permutation_musical_structure(perm):
    """Analyze what musical generator produces this permutation."""
    steps = [(perm[(i+1) % 12] - perm[i]) % 12 for i in range(12)]
    # Check if it's generated by a single interval
    for gen in range(1, 12):
        if math.gcd(gen, 12) == 1:  # generator must be coprime to 12
            test = [0]
            curr = 0
            for _ in range(11):
                curr = (curr + gen) % 12
                test.append(curr)
            if test == list(perm):
                return f"Generated by +{gen} semitones ({CONSONANCE_MAP[gen]})"
    return f"Steps: {steps}"


