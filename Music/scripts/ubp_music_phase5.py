def run_ve():
    print(f"\n{'=' * 80}")
    print("PHASE V-E: DIMENSIONALITY ANALYSIS — What information is in each 8-bit block?")
    print(f"{'=' * 80}")

    cw_map = encode_pitch_cw_map(COF_ORDER)

    print(f"\n  Each 24-bit codeword has 3 blocks of 8 bits (R, G, B in hex).")
    print(f"  Block 0 (bits 0-7)  = Red channel   = 'Noumenal core'")
    print(f"  Block 1 (bits 8-15) = Green channel = 'Phenomenal projection'")
    print(f"  Block 2 (bits 16-23)= Blue channel  = 'Leech shadow'")

    print(f"\n  {'Pitch':>5s} | {'CoF pos':>7s} | {'R (0-7)':>8s} | {'G (8-15)':>9s} | {'B (16-23)':>10s} | {'Total HW':>9s}")
    print(f"  {'-'*5} | {'-'*7} | {'-'*8} | {'-'*9} | {'-'*10} | {'-'*9}")

    for pc in range(12):
        cw = cw_map[pc]
        r_hw = sum(cw[0:8])
        g_hw = sum(cw[8:16])
        b_hw = sum(cw[16:24])
        pos = COF_ORDER.index(pc)
        print(f"  {PITCH_NAMES[pc]:>5s} | {pos:>7d} | {r_hw:>8d} | {g_hw:>9d} | {b_hw:>10d} | {r_hw+g_hw+b_hw:>9d}")

    # Average per block
    print(f"\n  Block weight statistics (11 non-zero pitches):")
    r_weights = [sum(cw_map[pc][0:8]) for pc in range(12) if pc != 0]
    g_weights = [sum(cw_map[pc][8:16]) for pc in range(12) if pc != 0]
    b_weights = [sum(cw_map[pc][16:24]) for pc in range(12) if pc != 0]
    print(f"    R block: avg={sum(r_weights)/len(r_weights):.2f}, range=[{min(r_weights)},{max(r_weights)}]")
    print(f"    G block: avg={sum(g_weights)/len(g_weights):.2f}, range=[{min(g_weights)},{max(g_weights)}]")
    print(f"    B block: avg={sum(b_weights)/len(b_weights):.2f}, range=[{min(b_weights)},{max(b_weights)}]")

    # Key question: how much of the Hamming distance is in each block?
    print(f"\n  HAMMING DISTANCE DECOMPOSITION BY BLOCK (CoF encoding):")
    print(f"  For each interval type, what fraction of dH is in each block?")

    by_interval_blocks = {}
    for pc_a, pc_b in combinations(range(12), 2):
        st = min((pc_b - pc_a) % 12, (pc_a - pc_b) % 12)
        if st == 0: continue
        r_hd = sum(cw_map[pc_a][i] ^ cw_map[pc_b][i] for i in range(8))
        g_hd = sum(cw_map[pc_a][i] ^ cw_map[pc_b][i] for i in range(8, 16))
        b_hd = sum(cw_map[pc_a][i] ^ cw_map[pc_b][i] for i in range(16, 24))
        by_interval_blocks.setdefault(st, []).append((r_hd, g_hd, b_hd))

    print(f"\n  {'Interval':>8s} | {'CR':>3s} | {'Avg R':>6s} | {'Avg G':>6s} | {'Avg B':>6s} | {'Total':>6s} | {'%R':>5s} | {'%G':>5s} | {'%B':>5s}")
    print(f"  {'-'*8} | {'-'*3} | {'-'*6} | {'-'*6} | {'-'*6} | {'-'*6} | {'-'*5} | {'-'*5} | {'-'*5}")

    for st in range(1, 7):
        blocks = by_interval_blocks.get(st, [])
        if not blocks: continue
        avg_r = sum(b[0] for b in blocks) / len(blocks)
        avg_g = sum(b[1] for b in blocks) / len(blocks)
        avg_b = sum(b[2] for b in blocks) / len(blocks)
        total = avg_r + avg_g + avg_b
        name = CONSONANCE_MAP[st]
        cr = CONSONANCE_RANK[st]
        pr = avg_r/total*100 if total > 0 else 0
        pg = avg_g/total*100 if total > 0 else 0
        pb = avg_b/total*100 if total > 0 else 0
        print(f"  {name:>8s} | {cr:>3d} | {avg_r:>6.2f} | {avg_g:>6.2f} | {avg_b:>6.2f} | {total:>6.2f} | {pr:>4.0f}% | {pg:>4.0f}% | {pb:>4.0f}%")


