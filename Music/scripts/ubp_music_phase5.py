    results = []
    for name, pcs, expected in chords:
        distances = []
        max_interval = 0
        for a, b in combinations(pcs, 2):
            hd = sum(x ^ y for x, y in zip(cw_map[a], cw_map[b]))
            distances.append(hd)
            st = min((b-a)%12, (a-b)%12)
            max_interval = max(max_interval, st)
        avg = sum(distances)/len(distances) if distances else 0
        var = sum((d-avg)**2 for d in distances)/len(distances) if distances else 0
        print(f"  {name:>12s} | {len(pcs):>6d} | {avg:>7.2f} | {var:>7.2f} | {min(distances) if distances else 0:>7d} | {max(distances) if distances else 0:>7d} | {max_interval:>6d} | {expected:>10s}")
        results.append({"name": name, "expected": expected, "avg_dh": avg, "var_dh": var, "max_iv": max_interval, "n": len(pcs)})

    # The problem: we can't compare chords of different sizes directly.
    # But within same-size chords:
    print(f"\n  SAME-SIZE COMPARISONS:")
    for size in [3, 4, 6]:
        subset = [r for r in results if r["n"] == size]
        if len(subset) < 2:
            continue
        print(f"\n  {size}-note chords:")
        cons_map = {"Consonant": 1, "Moderate": 2, "Mixed": 3, "Ambiguous": 3, "Dissonant": 4}
